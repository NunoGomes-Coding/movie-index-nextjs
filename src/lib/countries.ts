export type LangCode = keyof typeof mapping;
export type CountryCode = (typeof mapping)[LangCode];

export function MapLangToCountry(lang_code: string): CountryCode | undefined {
  return mapping[lang_code as LangCode].toUpperCase();
}

export function hasCountry(lang_code: string): boolean {
  return (
    Object.keys(mapping).includes(lang_code) &&
    Countries.includes(mapping[lang_code as LangCode].toUpperCase())
  );
}
